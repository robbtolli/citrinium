import 'dart:convert';
import 'dart:io';

import 'package:citrine_core/citrine_core.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

void main() {
  late Directory tempDir;

  setUp(() async {
    tempDir = await Directory.systemTemp.createTemp('citrine_cli_mcp_test_');
    final note = File(p.join(tempDir.path, 'daily', '2026-11-14.md'));
    await note.create(recursive: true);
    await note.writeAsString(
      '# 2026-11-14\n- [ ] File taxes 📅 2026-11-14 <!-- citrine:task=t_cli_1 -->\n',
    );
  });

  tearDown(() async {
    if (await tempDir.exists()) {
      await tempDir.delete(recursive: true);
    }
  });

  test('CitrineCliRunner supports schema, tasks create/list/update, notes, and dataview export', () async {
    final cli = CitrineCliRunner(
      vaultPath: tempDir.path,
      nowProvider: () => DateTime.utc(2026, 11, 14, 10, 0),
    );

    final schemaOut = StringBuffer();
    final err = StringBuffer();
    expect(await cli.run(['schema'], out: schemaOut, err: err), 0);
    final schemaJson = jsonDecode(schemaOut.toString()) as Map;
    expect(schemaJson['schemaVersion'], 2);

    final createOut = StringBuffer();
    expect(
      await cli.run(
        ['tasks', 'create', '--text', 'Call dentist', '--due', '2026-11-14'],
        out: createOut,
        err: err,
      ),
      0,
    );
    final created = jsonDecode(createOut.toString()) as Map;
    expect(created['sourceRelPath'], isNull);
    final taskId = created['taskId'] as String;

    final updateOut = StringBuffer();
    expect(
      await cli.run(
        ['tasks', 'update', '--id', taskId, '--state', 'completed'],
        out: updateOut,
        err: err,
      ),
      0,
    );
    final updated = jsonDecode(updateOut.toString()) as Map;
    expect(updated['state'], 'completed');

    final exportOut = StringBuffer();
    expect(
      await cli.run(
        [
          'dataview',
          'export',
          '--view',
          'dueToday',
          '--date',
          '2026-11-14',
          '--out',
          'exports/today.md',
        ],
        out: exportOut,
        err: err,
      ),
      0,
    );
    final exportedFile = File(p.join(tempDir.path, 'exports', 'today.md'));
    expect(await exportedFile.exists(), isTrue);
    final exportedText = await exportedFile.readAsString();
    expect(exportedText, contains('Static snapshot generated by Citrine'));
    expect(exportedText, contains('will not auto-update'));
    expect(exportedText, contains('File taxes'));
  });

  test('CitrineMcpServer handles initialize, tools/list, tools/call, and resources', () async {
    final server = CitrineMcpServer(
      vaultPath: tempDir.path,
      nowProvider: () => DateTime.utc(2026, 11, 14, 10, 0),
    );
    await server.open();
    try {
      final initResp = await server.handleMessage({
        'jsonrpc': '2.0',
        'id': 1,
        'method': 'initialize',
        'params': {},
      });
      expect(initResp!['result'], isA<Map<String, Object?>>());

      final listTools = await server.handleMessage({
        'jsonrpc': '2.0',
        'id': 2,
        'method': 'tools/list',
      });
      final tools = (listTools!['result'] as Map<String, Object?>)['tools'] as List;
      expect(
        tools.map((t) => (t as Map<String, Object?>)['name']),
        contains('create_task'),
      );

      final createResp = await server.handleMessage({
        'jsonrpc': '2.0',
        'id': 3,
        'method': 'tools/call',
        'params': {
          'name': 'create_task',
          'arguments': {'text': 'MCP created task', 'horizon': 'weekly'},
        },
      });
      final content = ((createResp!['result'] as Map)['content'] as List).first as Map;
      final createdTask = jsonDecode(content['text'] as String) as Map;
      expect(createdTask['text'], 'MCP created task');
      expect(createdTask['sourceRelPath'], isNull);

      final schemaRes = await server.handleMessage({
        'jsonrpc': '2.0',
        'id': 4,
        'method': 'resources/read',
        'params': {'uri': 'citrine://schema'},
      });
      final contents = ((schemaRes!['result'] as Map)['contents'] as List).first as Map;
      expect(contents['text'] as String, contains('citrine:task'));
    } finally {
      await server.close();
    }
  });
}
